"""Builds each sandbox experiment's figures.js from the shared stage kit and its own body.

    python3 ch99/_kit/build.py

kit.js (the free-style stage), ls.js (the lesson kit in the app's style) and the NN.N.js files are the sources; ch99/NN.N/figures.js is written from them.
"""
import pathlib
here = pathlib.Path(__file__).parent
KITS = {"xp": (here / "kit.js").read_text(), "ls": (here / "ls.js").read_text()}
for body in sorted(here.glob("99.*.js")):
    sec = body.stem
    src = body.read_text()
    kit = KITS["ls" if src.startswith("/* kit: ls */") else "xp"]
    out = here.parent / sec / "figures.js"
    out.parent.mkdir(exist_ok=True)
    out.write_text(
        "/* SANDBOX, not part of the book. GENERATED by ch99/_kit/build.py from a kit in _kit/ and _kit/%s.js: edit those. */\n"
        "window.OMNISTAX_FIGURES = window.OMNISTAX_FIGURES || {};\n"
        "window.OMNISTAX_FIGURES['%s'] = function (root, F) {\n%s\n%s};\n" % (sec, sec, kit, src)
    )
    print("wrote", out.relative_to(here.parent.parent))
