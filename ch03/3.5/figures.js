const PRIORITY = { '+': 1, '-': 1, '*': 2, '/': 2, '^': 3 };
const priority = (o) => (o[0] === 'u' ? 4 : o in PRIORITY ? PRIORITY[o] : -1);
const leftAssoc = (o) => !(o[0] === 'u' || o === '^');
const isOp = (c) => '+-*/^'.includes(c);
const isUnary = (c) => c === '+' || c === '-';
const isAlnum = (c) => /[0-9A-Za-z]/.test(c);
/* how an operator reads on the canvas: a typographic minus, and a unary one marked */
const sym = (o) => (o === '-' ? '−' : o);
const show = (o) => (o[0] === 'u' ? `unary ${sym(o.slice(1))}` : sym(o));
const word = (o) => (o === '(' ? 'the opening bracket' : show(o));
/* a number as the canvas writes it: a typographic minus, and in brackets where it is an operand */
const num = (v) => (v < 0 ? `−${-v}` : String(v));
const operand = (v) => (v < 0 ? `(${num(v)})` : num(v));
const apply = (o, st) => {
  if (o[0] === 'u') { const l = st.pop(), v = o[1] === '-' ? -l : l; st.push(v); return { v, how: `${sym(o.slice(1))}(${num(l)}) = ${num(v)}` }; }
  const r = st.pop(), l = st.pop();
  const v = o === '+' ? l + r : o === '-' ? l - r : o === '*' ? l * r : o === '/' ? Math.trunc(l / r) : l ** r;
  st.push(v);
  return { v, how: `${operand(l)} ${sym(o)} ${operand(r)} = ${num(v)}` };
};

