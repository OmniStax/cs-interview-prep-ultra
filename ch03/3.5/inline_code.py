"""Write sim-two-stack-parser's code panel into figures.js, between its generated markers.

C++: cp-algorithms' `evaluate` from its listing expression_parsing_unary, read from the cached page, with its
`while` condition replaced by the general one cp-algorithms prints under Right-associativity (set at the
listing's indentation); every other line as printed. Python, Java and JavaScript: the AI's line-for-line
translations in code/panel.*. code/panel.cpp is rewritten too, for the cross-language test.

    python3 -I ch03/3.5/inline_code.py
"""
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
BOOK = os.path.dirname(os.path.dirname(HERE))
PAGE = open(os.path.join(BOOK, 'sources/_cache/cpa/src/string/expression_parsing.md'), encoding='utf-8').read()


def panel_cpp():
    unary = re.search(r'```\{\.cpp file=expression_parsing_unary\}\n(.*?)\n```', PAGE, re.S).group(1)
    ev = unary[unary.index('int evaluate(string& s) {'):]
    general = re.findall(r'```cpp\n(.*?)\n```', PAGE, re.S)[1].split('\n')
    old = re.search(r'            while \(!op\.empty\(\) && \(\n.*?\n.*?\n                \)\) \{', ev, re.S).group(0)
    new = '\n'.join(' ' * 12 + l for l in general) + ' {'
    out = ev.replace(old, new)
    assert out != ev and out.count('left_assoc') == 2
    return out


def main():
    cpp = panel_cpp()
    open(os.path.join(HERE, 'code/panel.cpp'), 'w', encoding='utf-8').write(cpp + '\n')
    rd = lambda n: open(os.path.join(HERE, 'code', n), encoding='utf-8').read().rstrip('\n')  # noqa: E731
    gen = ('/* BEGIN generated by inline_code.py: the panel in four languages (C++ cp-algorithms\' evaluate with its general\n'
           '   while condition; Python, Java and JavaScript the AI\'s translations) */\n'
           f'const SRC = {{\n  python: {json.dumps(rd("panel.py"))},\n  java: {json.dumps(rd("panel.java"))},\n'
           f'  cpp: {json.dumps(cpp)},\n  javascript: {json.dumps(rd("panel.js"))},\n}};\n/* END generated */')
    path = os.path.join(HERE, 'figures.js')
    js = open(path, encoding='utf-8').read()
    js2 = re.sub(r'/\* BEGIN generated by inline_code\.py.*?/\* END generated \*/', lambda m: gen, js, flags=re.S)
    assert js2 != js or gen in js, 'markers not found'
    open(path, 'w', encoding='utf-8').write(js2)
    print(f'{path}: panel written ({cpp.count(chr(10)) + 1} C++ lines)')


if __name__ == '__main__':
    main()
