/* elements by identity between two frames: where each is drawn and how opaque. `at(state, id)` gives an
   element's place in a state or null; `from(id)` where an arriving element comes from, `to(id)` where a
   leaving one goes */
function morph(prev, cur, k, at, from, to) {
  const out = [], seen = new Set();
  cur.ids.forEach((id) => {
    seen.add(id);
    const q = at(cur, id), p = prev.ids.includes(id) ? at(prev, id) : null;
    if (p) out.push({ id, x: lerp(p.x, q.x, k), y: lerp(p.y, q.y, k), a: 1 });
    else { const f = from(id, q); out.push({ id, x: lerp(f.x, q.x, k), y: lerp(f.y, q.y, k), a: k, arriving: true }); }
  });
  prev.ids.forEach((id) => {
    if (seen.has(id)) return;
    const p = at(prev, id), t = to(id, p);
    out.push({ id, x: lerp(p.x, t.x, k), y: lerp(p.y, t.y, k), a: 1 - k, leaving: true });
  });
  return out;
}

