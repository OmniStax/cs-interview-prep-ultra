#!/usr/bin/env python3
"""Write cp-algorithms' C++ snippets into the code panels of 3.4's three cpa Sims, from the source cache.

cp-algorithms prints each structure of data_structures/stack_queue_modification as four fenced C++ snippets
(the declaration, then one per operation). Each panel shows one structure's snippets one after the other, in the
page's order, with a blank line between them, where the page's list of operations stood (plan question 2). This
reads them from the page, drops trailing blanks, and writes the three strings between the generated markers in
figures.js, so no line of the source's code is typed by hand. It prints each panel numbered, the lines the
figures' blocks and traces name.

    python3 -I ch03/3.4/inline_code.py
"""
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
BOOK = os.path.dirname(os.path.dirname(HERE))
PAGE = os.path.join(BOOK, 'sources/_cache/cpa/src/data_structures/stack_queue_modification.md')
PANELS = [('CPA_STACK', '## Stack modification'), ('CPA_M1', '## Queue modification (method 1)'),
          ('CPA_M3', '## Queue modification (method 3)')]


def snippets(md, heading):
    a = md.index(heading + '\n')
    b = md.find('\n## ', a + len(heading))
    blocks = re.findall(r'```cpp\n(.*?)\n```', md[a:b if b > 0 else len(md)], re.S)
    if len(blocks) != 4:
        raise SystemExit(f'{heading}: expected four C++ snippets, found {len(blocks)}')
    return '\n\n'.join('\n'.join(l.rstrip() for l in s.split('\n')) for s in blocks)


def main():
    md = open(PAGE, encoding='utf-8').read()
    path = os.path.join(HERE, 'figures.js')
    src = open(path, encoding='utf-8').read()
    begin = src.index('/* BEGIN generated by inline_code.py')
    end = src.index('/* END generated */')
    head = src[begin:src.index('\n', begin) + 1]
    body = head
    for name, heading in PANELS:
        code = snippets(md, heading)
        body += f'const {name} = {json.dumps(code)};\n'
        print(name)
        for i, l in enumerate(code.split('\n'), 1):
            print(f'{i:3} {l}')
    open(path, 'w', encoding='utf-8').write(src[:begin] + body + src[end:])


if __name__ == '__main__':
    main()
