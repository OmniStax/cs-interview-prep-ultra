#!/usr/bin/env python3
"""Write sim-dllist's code panel into figures.js, from the source cache.

The panel is ODS's getNode(i), addBefore(w,x) and remove(w), the three members the figure steps through: in
Python as python/ods/dllist.py has them (get_node, add_before, _remove; get_node with the spec's port of n/2),
in Java and C++ as ODS's extractors print them (tools/ods_listing.py), and in JavaScript as build_spec.py
translates them. The four strings go between the generated markers in figures.js, so no line of the panel is
typed by hand and the panel shows the same code as the text's code sets.

    python3 -I ch02/2.6/inline_code.py
"""
import importlib.util
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
MEMBERS = ['DLList.getNode(i)', 'DLList.addBefore(w,x)', 'DLList.remove(w)']


def main():
    sp = importlib.util.spec_from_file_location('build_spec', os.path.join(HERE, 'build_spec.py'))
    spec = importlib.util.module_from_spec(sp)
    sp.loader.exec_module(spec)
    sets = [spec.listing(m) for m in MEMBERS]
    src = {lang: '\n\n'.join(s[lang] for s in sets) for lang in ('python', 'java', 'cpp', 'javascript')}
    path = os.path.join(HERE, 'figures.js')
    js = open(path, encoding='utf-8').read()
    begin = js.index('/* BEGIN generated by inline_code.py')
    end = js.index('/* END generated */')
    head = js[begin:js.index('\n', begin) + 1]
    body = head + ''.join(f'  const ODS_{k.upper()} = {json.dumps(v)};\n' for k, v in src.items()) + '  '
    open(path, 'w', encoding='utf-8').write(js[:begin] + body + js[end:])
    for k, v in src.items():
        print(f'--- {k}')
        for n, line in enumerate(v.split('\n'), 1):
            print(f'{n:3} {line}')


if __name__ == '__main__':
    main()
