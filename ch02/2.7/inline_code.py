#!/usr/bin/env python3
"""Write cp-algorithms' two Java snippets into sim-rho's code panel, from the source cache.

cp-algorithms prints Step 2 with two fenced Java blocks: hasCycle(head), then the reset-and-walk fragment.
This reads both from the page, sets them one after the other with a blank line between them (the panel shows
them as one listing, where the two stood), turns the second block's tabs into four spaces (as 1.3's ODS code
did) and drops trailing blanks, and writes the string between the generated markers in figures.js, so no
line of the source's code is typed by hand.

    python3 -I ch02/2.7/inline_code.py
"""
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
BOOK = os.path.dirname(os.path.dirname(HERE))
PAGE = os.path.join(BOOK, 'sources/_cache/cpa/src/others/tortoise_and_hare.md')


def main():
    md = open(PAGE, encoding='utf-8').read()
    blocks = re.findall(r'```java\n(.*?)\n```', md, re.S)
    if len(blocks) != 2:
        raise SystemExit(f'expected two Java blocks, found {len(blocks)}')
    java = '\n\n'.join('\n'.join(l.replace('\t', '    ').rstrip() for l in b.split('\n')) for b in blocks)
    path = os.path.join(HERE, 'figures.js')
    src = open(path, encoding='utf-8').read()
    begin = src.index('/* BEGIN generated by inline_code.py')
    end = src.index('/* END generated */')
    head = src[begin:src.index('\n', begin) + 1]
    body = head + f'const CPA_JAVA = {json.dumps(java)};\n'
    open(path, 'w', encoding='utf-8').write(src[:begin] + body + src[end:])
    for i, l in enumerate(java.split('\n'), 1):
        print(f'{i:3} {l}')


if __name__ == '__main__':
    main()
