  const R = L >= 3 && o.smin ? Math.min(R0, Rfit) : R0;
  const right = L >= 2 ? 2 * R + BW / 2 : L === 1 ? BW / 2 + 2 * loopR : BW / 2 + 130;    /* past the tail's last stop */
  const headRoom = BW / 2 + 170;
  const tailN = L === 0 ? n - 1 : a;
  const room = o.right - o.left - headRoom - right;
  const s = tailN > 0 ? Math.min(o.s || 150, room / tailN) : 0;
  const width = headRoom + tailN * s + right;
  const x0 = (o.left + o.right) / 2 - width / 2 + headRoom;
