#!/usr/bin/env python3
"""Write ODS's Simple.snippet() into sim-loop-count's code panel, from the source cache.

ODS prints the snippet from java/junk/Simple.java (\\javaimport{junk/Simple.snippet()}) and cpp/Simple.h
(\\cppimport{ods/Simple.snippet()}). This reads the method from each file (Java: the snippet() method; C++:
the out-of-class definition with its template line), turns ODS's tabs into four spaces and drops trailing
blanks, and writes the two strings between the generated markers in figures.js, so the panel shows ODS's
code and no line of it is typed by hand.

    python3 -I ch01/1.3/inline_code.py
"""
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
BOOK = os.path.dirname(os.path.dirname(HERE))
ODS = os.path.join(BOOK, 'sources/_cache/ods')


def method(lines, start_pat):
    """From the line matching start_pat to the line that closes its brace, tabs as four spaces."""
    i = next(k for k, l in enumerate(lines) if re.search(start_pat, l))
    depth, out = 0, []
    for l in lines[i:]:
        out.append(l.replace('\t', '    ').rstrip())
        depth += l.count('{') - l.count('}')
        if depth == 0 and '{' in ''.join(out):
            break
    # the method as it stands on its own: its indentation inside the class taken off
    pad = min(len(l) - len(l.lstrip()) for l in out if l.strip())
    return '\n'.join(l[pad:] for l in out)


def main():
    java = open(os.path.join(ODS, 'java/junk/Simple.java'), encoding='utf-8').read().split('\n')
    cpp = open(os.path.join(ODS, 'cpp/Simple.h'), encoding='utf-8').read().split('\n')
    j = method(java, r'void snippet\(\)')
    k = next(i for i, l in enumerate(cpp) if re.search(r'Simple<T>::snippet\(\)', l))
    c = cpp[k - 1].rstrip() + '\n' + method(cpp, r'Simple<T>::snippet\(\)')    # the template line above it
    path = os.path.join(HERE, 'figures.js')
    src = open(path, encoding='utf-8').read()
    begin = src.index('/* BEGIN generated by inline_code.py')
    end = src.index('/* END generated */')
    head = src[begin:src.index('\n', begin) + 1]
    indent = '  '
    body = (head + f'{indent}const ODS_JAVA = {json.dumps(j)};\n' + f'{indent}const ODS_CPP = {json.dumps(c)};\n' + indent)
    open(path, 'w', encoding='utf-8').write(src[:begin] + body + src[end:])
    print(j, '\n---\n', c, sep='')


if __name__ == '__main__':
    main()
